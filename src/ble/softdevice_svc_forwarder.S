.syntax unified
.thumb

.macro SOFTDEVICE_FORWARD handler, vector_offset
.global \handler
.type \handler, %function
\handler:
    ldr r0, =(0x00001000 + \vector_offset)
    ldr r0, [r0]
    bx r0
.size \handler, . - \handler
.endm

